'use client';

import { useEffect, useState } from 'react';
import Link from 'next/link';
import { toast } from 'sonner';
import { KeyRound, ShieldCheck, ShieldAlert, MonitorSmartphone, ListChecks } from 'lucide-react';
import PageHeader from '@/components/common/PageHeader';
import ConfirmModal from '@/components/modals/ConfirmModal';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { authApi } from '@/lib/api/auth';
import { sessionsApi } from '@/lib/api/sessions';
import { useAuthStore } from '@/lib/store/authStore';
import { useUIStore } from '@/lib/store/uiStore';

const errText = (e: unknown) =>
  (e as { response?: { data?: { error?: { message?: string } } } })?.response?.data?.error?.message
  ?? (e as { message?: string })?.message ?? 'Something went wrong';

function PasswordCard({ email }: { email: string }) {
  const [busy, setBusy] = useState(false);
  const [sent, setSent] = useState(false);
  const send = async () => {
    setBusy(true);
    try {
      await authApi.forgotPassword({ email });
      setSent(true);
      toast.success('Check your inbox for the reset link.');
    } catch (e) { toast.error(errText(e)); } finally { setBusy(false); }
  };
  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-sm"><KeyRound className="h-4 w-4" />Password</CardTitle>
        <CardDescription className="text-xs">For your safety a reset link is emailed to {email}. Nobody else can change your password from here.</CardDescription>
      </CardHeader>
      <CardContent>
        <Button variant="outline" onClick={send} disabled={busy}>{sent ? 'Send it again' : 'Email me a reset link'}</Button>
      </CardContent>
    </Card>
  );
}

function TwoStepCard() {
  const user = useAuthStore((s) => s.user);
  const setUser = useAuthStore((s) => s.setUser);
  const [setup, setSetup] = useState<{ qrCodeUrl: string; secret: string; recoveryCodes: string[] } | null>(null);
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [confirmOff, setConfirmOff] = useState(false);
  const enabled = !!user?.mfaEnabled;

  const refreshUser = async () => {
    const me = (await authApi.me())?.data?.data;
    if (me) setUser(me);
  };

  const start = async () => {
    setBusy(true);
    try { setSetup((await authApi.mfaSetupStart()).data.data); setCode(''); }
    catch (e) { toast.error(errText(e)); } finally { setBusy(false); }
  };
  const confirm = async () => {
    setBusy(true);
    try {
      await authApi.mfaConfirm(code.trim());
      toast.success('Two-step sign-in is on.');
      setSetup(null);
      await refreshUser();
    } catch (e) { toast.error(errText(e)); } finally { setBusy(false); }
  };
  const turnOff = async () => {
    setBusy(true);
    try { await authApi.mfaDisable(''); toast.success('Two-step sign-in is off.'); await refreshUser(); }
    catch (e) { toast.error(errText(e)); } finally { setBusy(false); setConfirmOff(false); }
  };

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-sm">
          {enabled ? <ShieldCheck className="h-4 w-4 text-green-600" /> : <ShieldAlert className="h-4 w-4 text-amber-500" />}
          Two-step sign-in
          <Badge variant={enabled ? 'success' : 'secondary'} className="text-[10px]">{enabled ? 'On' : 'Off'}</Badge>
        </CardTitle>
        <CardDescription className="text-xs">Use an authenticator app (Google Authenticator, 1Password, Authy) so a stolen password alone cannot open this console.</CardDescription>
      </CardHeader>
      <CardContent className="space-y-4">
        {!setup && !enabled && <Button onClick={start} disabled={busy}>Set up authenticator app</Button>}
        {!setup && enabled && <Button variant="outline" onClick={() => setConfirmOff(true)} disabled={busy}>Turn off</Button>}

        {setup && (
          <div className="space-y-4 rounded-lg border p-4">
            <p className="text-sm">1. Scan this code with your authenticator app.</p>
            {/* eslint-disable-next-line @next/next/no-img-element -- data: URL generated by the server */}
            <img src={setup.qrCodeUrl} alt="Authenticator QR code" className="h-44 w-44 rounded-md border bg-white p-2" />
            <p className="text-xs text-muted-foreground">Can&apos;t scan? Enter this key manually: <code className="break-all rounded bg-muted px-1.5 py-0.5">{setup.secret}</code></p>
            <div>
              <p className="mb-2 text-sm">2. Save your recovery codes somewhere safe. Each works once if you lose your phone.</p>
              <div className="grid grid-cols-2 gap-1.5 rounded-md bg-muted p-3 font-mono text-xs sm:grid-cols-4">
                {setup.recoveryCodes.map((c) => <span key={c}>{c}</span>)}
              </div>
            </div>
            <div className="space-y-1.5">
              <Label htmlFor="mfa-code" className="text-sm">3. Enter the 6-digit code from the app to finish</Label>
              <div className="flex gap-2">
                <Input id="mfa-code" inputMode="numeric" autoComplete="one-time-code" maxLength={6} value={code} onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))} className="w-40 font-mono tracking-widest" placeholder="123456" />
                <Button onClick={confirm} disabled={busy || code.length !== 6}>Turn on</Button>
                <Button variant="ghost" onClick={() => setSetup(null)} disabled={busy}>Cancel</Button>
              </div>
              <p className="text-xs text-muted-foreground">Nothing changes on your account until this code is accepted, so you cannot lock yourself out.</p>
            </div>
          </div>
        )}
      </CardContent>
      <ConfirmModal
        open={confirmOff}
        onOpenChange={setConfirmOff}
        title="Turn off two-step sign-in?"
        description="Your account will be protected by your password alone."
        confirmLabel="Turn off"
        isLoading={busy}
        onConfirm={turnOff}
      />
    </Card>
  );
}

function SessionsCard() {
  const [busy, setBusy] = useState(false);
  const [confirm, setConfirm] = useState(false);
  const signOutOthers = async () => {
    setBusy(true);
    try { await sessionsApi.revokeAllOthers(); toast.success('Signed out of all your other devices.'); }
    catch (e) { toast.error(errText(e)); } finally { setBusy(false); setConfirm(false); }
  };
  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2 text-sm"><MonitorSmartphone className="h-4 w-4" />Devices and sessions</CardTitle>
        <CardDescription className="text-xs">See where you are signed in, and end sessions you do not recognise.</CardDescription>
      </CardHeader>
      <CardContent className="flex flex-wrap gap-2">
        <Button variant="outline" asChild><Link href="/sessions">View my sessions</Link></Button>
        <Button variant="outline" asChild><Link href="/login-activity"><ListChecks className="mr-2 h-4 w-4" />Sign-in activity</Link></Button>
        <Button variant="outline" onClick={() => setConfirm(true)} disabled={busy}>Sign out other devices</Button>
      </CardContent>
      <ConfirmModal open={confirm} onOpenChange={setConfirm} title="Sign out all other devices?" description="This device stays signed in. Everywhere else will need to sign in again." confirmLabel="Sign them out" isLoading={busy} onConfirm={signOutOthers} />
    </Card>
  );
}

export default function SecuritySettingsPage() {
  const user = useAuthStore((s) => s.user);
  const setBreadcrumbs = useUIStore((s) => s.setBreadcrumbs);
  useEffect(() => { setBreadcrumbs([{ label: 'Settings', href: '/settings' }, { label: 'Security' }]); }, [setBreadcrumbs]);

  return (
    <div className="space-y-6">
      <PageHeader title="Security" description="Protect your account and see where it is in use." />
      <div className="grid gap-6">
        {user?.email && <PasswordCard email={user.email} />}
        <TwoStepCard />
        <SessionsCard />
      </div>
    </div>
  );
}
