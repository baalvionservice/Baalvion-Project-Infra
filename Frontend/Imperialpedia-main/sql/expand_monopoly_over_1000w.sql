<h2>1. Why Natural Monopolies Form (Economies of Scale)</h2>
<p>A natural monopoly forms when the minimum efficient scale (MES) of production is so large that only one firm can operate at the lowest possible long-run average cost curve. Constructing parallel water mains, electrical wires, or railway tracks across a single city would double capital expenditures without adding consumer utility — resulting in wasteful economic duplication.</p>

<h2>2. Why Pure Monopolies Form (Barriers & Strategy)</h2>
<p>Pure monopolies do not depend on natural infrastructure scale. Instead, they arise because the monopolist controls key raw materials, holds exclusive patents, or uses predatory pricing to drive competitors out of business. Pure monopolies often charge high monopoly rents (P >> MC) until antitrust authorities intervene or patents expire.</p>

<h2>Pricing Models in Natural Monopolies</h2>
<p>Regulators use two main pricing strategies when overseeing natural utility monopolies:</p>
<ol>
<li><strong>Marginal Cost Pricing (P = MC):</strong> Achieves theoretical allocative efficiency, but forces the natural monopoly into a continuous operating loss because ATC > MC. Requires government subsidies funded by tax dollars.</li>
<li><strong>Average Cost Pricing (P = ATC):</strong> Allows the firm to earn a fair "normal" rate of return on invested capital without taxpayer subsidies, though creating a minor deadweight loss.</li>
<li><strong>Price Cap Regulation (RPI - X):</strong> Popular in utility regulation — allowing prices to rise by inflation (RPI) minus an expected efficiency gain (X), encouraging the utility firm to cut operating costs to keep profits.</li>
</ol>

<h2>Summary Evaluation for Economists & Analysts</h2>
<ul>
<li>Natural monopolies are protected by market physics (economies of scale); pure monopolies are protected by artificial or legal walls.</li>
<li>Regulatory policy seeks to manage natural monopolies via public utility commissions, while seeking to dismantle pure monopolies via antitrust enforcement.</li>
</ul>'
