"use client"

import { useCallback, useEffect, useState } from "react"
import { adminApi, type Draw } from "@/lib/api/engagement"

const input = "w-full bg-black/40 border border-white/10 rounded-lg p-2.5 text-sm text-white outline-none focus:border-red-500"
const when = (iso: string) => new Date(iso).toLocaleString("en-IN", { day: "numeric", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" })

export default function AdminLotteryPage() {
  const [draws, setDraws] = useState<Draw[]>([])
  const [error, setError] = useState("")
  const [busy, setBusy] = useState("")
  const [form, setForm] = useState({ title: "", state: "", prize: "", entryPoints: "600", maxEntriesPerUser: "5", winnersCount: "1", closesAt: "" })

  const load = useCallback(async () => {
    try { setError(""); setDraws((await adminApi.draws()).items) } catch (e) { setError(e instanceof Error ? e.message : "Could not load") }
  }, [])
  useEffect(() => { load() }, [load])

  const run = async (key: string, fn: () => Promise<unknown>, confirmText?: string) => {
    if (confirmText && !window.confirm(confirmText)) return
    setBusy(key); setError("")
    try { await fn(); await load() } catch (e) { setError(e instanceof Error ? e.message : "Failed") } finally { setBusy("") }
  }

  const create = (e: React.FormEvent) => {
    e.preventDefault()
    run("create", async () => {
      await adminApi.createDraw({ title: form.title, state: form.state || undefined, prize: form.prize, entryPoints: Number(form.entryPoints), maxEntriesPerUser: Number(form.maxEntriesPerUser), winnersCount: Number(form.winnersCount), closesAt: new Date(form.closesAt).toISOString() })
      setForm({ ...form, title: "", prize: "", closesAt: "" })
    })
  }

  return (
    <div className="max-w-4xl mx-auto space-y-8">
      <header>
        <h1 className="text-2xl font-bold text-white">Ticket draws</h1>
        <p className="text-sm text-gray-400 mt-1">Create a draw, open it, close it, then run it once. The random seed is generated by the server. Cancelling refunds every entry.</p>
      </header>
      {error && <div className="p-3 rounded-lg border border-red-500/40 bg-red-950/30 text-sm text-red-200">{error}</div>}

      <form onSubmit={create} className="rounded-xl border border-white/10 p-5 space-y-3">
        <h2 className="font-semibold text-white">New draw</h2>
        <input required className={input} placeholder="Title" value={form.title} onChange={(e) => setForm({ ...form, title: e.target.value })} />
        <input className={input} placeholder="State this draw is for (optional, e.g. Maharashtra)" value={form.state} onChange={(e) => setForm({ ...form, state: e.target.value })} />
        <input required className={input} placeholder="Prize (exactly what the winner gets)" value={form.prize} onChange={(e) => setForm({ ...form, prize: e.target.value })} />
        <div className="grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs text-gray-400">
          <label>Points per entry<input className={input} inputMode="numeric" value={form.entryPoints} onChange={(e) => setForm({ ...form, entryPoints: e.target.value.replace(/\D/g, "") })} /></label>
          <label>Max entries each<input className={input} inputMode="numeric" value={form.maxEntriesPerUser} onChange={(e) => setForm({ ...form, maxEntriesPerUser: e.target.value.replace(/\D/g, "") })} /></label>
          <label>Winners<input className={input} inputMode="numeric" value={form.winnersCount} onChange={(e) => setForm({ ...form, winnersCount: e.target.value.replace(/\D/g, "") })} /></label>
          <label>Closes<input required type="datetime-local" className={input} value={form.closesAt} onChange={(e) => setForm({ ...form, closesAt: e.target.value })} /></label>
        </div>
        <button disabled={busy === "create"} className="bg-red-600 text-white text-sm font-semibold px-5 py-2.5 rounded-lg disabled:opacity-50">Create as draft</button>
      </form>

      <div className="space-y-4">
        {draws.length === 0 && <p className="text-gray-500 text-sm">No draws yet.</p>}
        {draws.map((d) => (
          <section key={d.id} className="rounded-xl border border-white/10 p-5">
            <div className="flex flex-wrap justify-between gap-2">
              <div>
                <h3 className="font-semibold text-white">{d.title}{d.state ? ` · ${d.state}` : ""}</h3>
                <p className="text-sm text-gray-400">{d.prize} · {d.entryPoints} pts/entry · {d.winnersCount} winner(s) · closes {when(d.closesAt)}</p>
                <p className="text-sm text-gray-400">{d.entries} entries from {d.members} member(s)</p>
              </div>
              <span className="text-xs uppercase font-bold text-red-300 self-start">{d.status}</span>
            </div>
            <div className="mt-3 flex flex-wrap gap-2 text-sm">
              {d.status === "draft" && <button disabled={!!busy} onClick={() => run(d.id, () => adminApi.drawAction(d.id, "open"))} className="border border-white/20 text-white px-4 py-2 rounded-lg">Open for entries</button>}
              {d.status === "open" && <button disabled={!!busy} onClick={() => run(d.id, () => adminApi.drawAction(d.id, "close"), "Close entries now?")} className="border border-white/20 text-white px-4 py-2 rounded-lg">Close entries</button>}
              {(d.status === "open" || d.status === "closed") && <button disabled={!!busy} onClick={() => run(d.id, () => adminApi.drawAction(d.id, "draw"), "Run the draw now? This can only be done once.")} className="bg-red-600 text-white px-4 py-2 rounded-lg">Run the draw</button>}
              {["draft", "open", "closed"].includes(d.status) && <button disabled={!!busy} onClick={() => run(d.id, () => adminApi.drawAction(d.id, "cancel"), "Cancel this draw and refund every entry?")} className="border border-red-500/40 text-red-300 px-4 py-2 rounded-lg">Cancel and refund</button>}
            </div>
            {d.status === "drawn" && (
              <div className="mt-4 text-sm text-gray-300">
                <p className="font-semibold text-white mb-1">Winners</p>
                <ul className="space-y-1">
                  {d.winners.map((w) => (
                    <li key={w.position} className="flex flex-wrap items-center gap-3">
                      <span>{w.position}. Member #{w.memberNumber ?? "—"} · ticket #{w.ticketNo}</span>
                      {w.claimed ? <span className="text-green-400">prize handed over</span> : w.entryId && <button disabled={!!busy} onClick={() => run(w.entryId!, () => adminApi.claimed(w.entryId!))} className="underline text-gray-300">Mark prize handed over</button>}
                    </li>
                  ))}
                </ul>
                {d.drawSeed && <p className="mt-2 text-xs text-gray-500 break-all">Seed: {d.drawSeed}</p>}
              </div>
            )}
          </section>
        ))}
      </div>
    </div>
  )
}
